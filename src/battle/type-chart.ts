/** Rejects unknown/TCG types, duplicates and incomplete defensive or offensive typing. */
export function assertPokemonTypes(types: readonly PokemonType[]): void {
  if (!Array.isArray(types) || types.length < 1 || types.length > 2) {
    throw new TypeError('Expected one or two Pokemon types')
  }
  for (const type of types) {
    if (!POKEMON_TYPES.includes(type)) throw new TypeError('Unknown Pokemon type')
  }
  if (new Set(types).size !== types.length) throw new TypeError('Duplicate Pokemon type')
}

export function getTypeEffectiveness(
  moveType: PokemonType,
  defenderTypes: readonly PokemonType[],
): TypeEffectiveness {
  if (!POKEMON_TYPES.includes(moveType)) throw new TypeError('Unknown move type')
  assertPokemonTypes(defenderTypes)
  return defenderTypes.reduce<number>(
    (factor, type) => factor * chart[moveType][POKEMON_TYPES.indexOf(type)],
    1,
  ) as TypeEffectiveness
}
